const smokeOpenAPI = `openapi: 3.0.3
info:
  title: test
  version: "1"
paths:
  /users:
    get:
      responses:
        "200":
          description: ok
`

// smokeLLM returns canned responses keyed by the exact system prompt. Each
// stage of the init pipeline has its own prompt, so a mismatch is a bug.
type smokeLLM struct{}

func (smokeLLM) Name() string { return "smoke" }

func (smokeLLM) GenerateStructured(
	_ context.Context, systemPrompt, _ string, _ any,
) (string, error) {
	switch systemPrompt {
	case globalSystemPrompt:
		return `{"assumptions":[],"seed":{},"common_setups":[]}`, nil
	case outlineSystemPrompt:
		return `{"setups":[],"scenarios":[{"id":"users-get","name":"Get users","purpose":"Read a user","apis":["GET {default}/users"]}]}`, nil
	case scenarioSystemPrompt:
		return `{"scenarios":[{"id":"users-get","steps":[{"call":"GET {default}/users","expect":200,"save":{"user_id":"body.id"}}]}]}`, nil
	case analysisSystemPrompt:
		return `{"analysis":"Generated by test."}`, nil
	default:
		return "", fmt.Errorf("unexpected prompt")
	}
}

// recordingStore delegates to the real store and captures what the pipeline
// asked it to write.
type recordingStore struct {
	inner domain.SuiteStore
	opts  []domain.WriteOptions
}

func (s *recordingStore) Load(ctx context.Context, dir string) (*domain.FileSet, error) {
	return s.inner.Load(ctx, dir)
}

func (s *recordingStore) Save(
	ctx context.Context, dir string, files *domain.FileSet, opts domain.WriteOptions,
) error {
	s.opts = append(s.opts, opts)
	return s.inner.Save(ctx, dir, files, opts)
}

type smokeClock struct{}

func (smokeClock) Now() time.Time {
	return time.Date(2026, 10, 26, 12, 0, 0, 0, time.UTC)
}

func TestExecuteInitSmoke(t *testing.T) {
	dir := t.TempDir()
	apiPath := filepath.Join(dir, "openapi.yaml")
	if err := os.WriteFile(apiPath, []byte(smokeOpenAPI), 0o644); err != nil {
		t.Fatalf("write openapi: %v", err)
	}
	outDir := filepath.Join(dir, "out")

	store := &recordingStore{inner: suitefile.NewStore()}
	g := NewGenerator(smokeLLM{}, sources.NewLoader(), store, smokeClock{})

	res, err := g.Execute(context.Background(), Request{
		APIs:        []domain.APIInput{{Server: "default", Path: apiPath}},
		OutputDir:   outDir,
		Concurrency: 1,
	})
	if err != nil {
		t.Fatalf("Execute: %v", err)
	}

	if res.Mode != ModeInitial {
		t.Errorf("Mode = %q, want %q", res.Mode, ModeInitial)
	}
	if res.Input != domain.InputOpenAPI {
		t.Errorf("Input = %q, want %q", res.Input, domain.InputOpenAPI)
	}
	if res.APITotal != 1 {
		t.Errorf("APITotal = %d, want 1", res.APITotal)
	}

	if len(store.opts) != 1 {
		t.Fatalf("Save called %d times, want 1", len(store.opts))
	}
	if store.opts[0].Mode != string(ModeInitial) {
		t.Errorf("WriteOptions.Mode = %q, want %q", store.opts[0].Mode, ModeInitial)
	}
	if !store.opts[0].Suite || !store.opts[0].Log || !store.opts[0].Track {
		t.Errorf("WriteOptions = %+v, want suite, log and track", store.opts[0])
	}

	for _, name := range []string{
		suitefile.SuiteFileName, suitefile.LogFileName, suitefile.TrackFileName,
	} {
		if _, err := os.Stat(filepath.Join(outDir, name)); err != nil {
			t.Errorf("%s missing: %v", name, err)
		}
	}

	loaded, err := suitefile.NewStore().Load(context.Background(), outDir)
	if err != nil {
		t.Fatalf("load suite files: %v", err)
	}
	if loaded.Suite == nil || loaded.Log == nil || loaded.Track == nil {
		t.Fatalf("loaded file set incomplete: suite=%v log=%v track=%v",
			loaded.Suite != nil, loaded.Log != nil, loaded.Track != nil)
	}

	suite := loaded.Suite
	if suite.Input != domain.InputOpenAPI {
		t.Errorf("suite.Input = %q, want %q", suite.Input, domain.InputOpenAPI)
	}
	if len(suite.Scenarios) != 1 {
		t.Fatalf("len(suite.Scenarios) = %d, want 1", len(suite.Scenarios))
	}
	steps := suite.Scenarios[0].Steps
	if len(steps) == 0 {
		t.Fatal("scenario has no steps")
	}
	if got := steps[0].Save["user_id"]; got != "body.id" {
		t.Errorf("Steps[0].Save[user_id] = %q, want %q", got, "body.id")
	}
}

// TestExecuteDryRunWritesNothing verifies that a dry run reports no writes and
// leaves a fresh output directory uncreated.
func TestExecuteDryRunWritesNothing(t *testing.T) {
	dir := t.TempDir()
	apiPath := filepath.Join(dir, "openapi.yaml")
	if err := os.WriteFile(apiPath, []byte(smokeOpenAPI), 0o644); err != nil {
		t.Fatalf("write openapi: %v", err)
	}
	outDir := filepath.Join(dir, "out")

	store := &recordingStore{inner: suitefile.NewStore()}
	g := NewGenerator(smokeLLM{}, sources.NewLoader(), store, smokeClock{})

	res, err := g.Execute(context.Background(), Request{
		APIs:        []domain.APIInput{{Server: "default", Path: apiPath}},
		OutputDir:   outDir,
		DryRun:      true,
		Concurrency: 1,
	})
	if err != nil {
		t.Fatalf("Execute: %v", err)
	}

	if !res.NoFilesWritten {
		t.Errorf("NoFilesWritten = false, want true")
	}
	if _, err := os.Stat(outDir); !os.IsNotExist(err) {
		t.Errorf("output directory %s exists after dry run (stat err = %v)", outDir, err)
	}
	if len(store.opts) != 0 {
		t.Errorf("Save called %d times, want 0", len(store.opts))
	}
}
